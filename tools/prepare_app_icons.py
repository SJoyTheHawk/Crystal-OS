#!/usr/bin/env python3
"""Resize app artwork into opaque, true-color LVGL image descriptors."""
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SOURCE = ROOT / "reference/app-icons/default_app_icon.jpg"
BUS_SOURCE = ROOT / "reference/app-icons/bus_app_icon.jpg"


def resize_rgb(source, size):
    pixels = subprocess.check_output([
        "ffmpeg", "-v", "error", "-i", str(source),
        "-vf", f"scale={size}:{size}:flags=lanczos",
        "-frames:v", "1", "-pix_fmt", "rgb24", "-f", "rawvideo", "pipe:1",
    ])
    expected = size * size * 3
    if len(pixels) != expected:
        raise ValueError(f"Unexpected {size}px output from {source.name}: {len(pixels)} bytes")
    return list(zip(pixels[0::3], pixels[1::3], pixels[2::3]))


def emit_bytes(data):
    return "".join(
        "  " + ", ".join(f"0x{value:02x}" for value in data[offset:offset + 16]) + ",\n"
        for offset in range(0, len(data), 16)
    )


def encode_rgb565(pixels):
    rgb565 = [(r >> 3) << 11 | (g >> 2) << 5 | (b >> 3) for r, g, b in pixels]
    return b"".join(value.to_bytes(2, "little") for value in rgb565)


def header():
    return f'''/* Generated by tools/prepare_app_icons.py. Native LVGL RGB565 pixels. */
#include "lvgl.h"

#if LV_COLOR_DEPTH != 16 || LV_COLOR_16_SWAP != 0
#error "Crystal OS app icons require RGB565 with LV_COLOR_16_SWAP disabled"
#endif

#ifndef LV_ATTRIBUTE_MEM_ALIGN
#define LV_ATTRIBUTE_MEM_ALIGN
#endif
#ifndef LV_ATTRIBUTE_LARGE_CONST
#define LV_ATTRIBUTE_LARGE_CONST
#endif
'''


def descriptor(name, map_name, size):
    return f'''const lv_img_dsc_t {name} = {{
  .header.cf = LV_IMG_CF_TRUE_COLOR,
  .header.always_zero = 0,
  .header.reserved = 0,
  .header.w = {size},
  .header.h = {size},
  .data_size = {size * size} * LV_COLOR_SIZE / 8,
  .data = {map_name},
}};
'''


def pixel_map(name, data):
    return f'''const LV_ATTRIBUTE_MEM_ALIGN LV_ATTRIBUTE_LARGE_CONST uint8_t {name}[] = {{
{emit_bytes(data)}}};
'''


def generate(source, output, name, size):
    pixels = resize_rgb(source, size)
    map_name = f"{name}_map"
    output.parent.mkdir(parents=True, exist_ok=True)
    text = header()
    text += pixel_map(map_name, encode_rgb565(pixels))
    text += descriptor(name, map_name, size)
    output.write_text(f"/* Lanczos resized from {source.relative_to(ROOT)}. */\n" + text)
    print(f"{size}x{size}: {output.relative_to(ROOT)}")


def generate_shared_default_112(image_assets):
    group = "middle"
    name = "esp_brookesia_image_middle_app_launcher_default_112_112"
    map_name = "crystal_default_app_icon_112_map"
    pixels = resize_rgb(DEFAULT_SOURCE, 112)
    middle = image_assets / f"{group}/{name}.c"
    middle.parent.mkdir(parents=True, exist_ok=True)
    middle_text = header()
    middle_text += pixel_map(map_name, encode_rgb565(pixels))
    middle_text += descriptor(name, map_name, 112)
    middle.write_text(f"/* Lanczos resized from {DEFAULT_SOURCE.relative_to(ROOT)}. */\n" + middle_text)

    large_name = "esp_brookesia_image_large_app_launcher_default_112_112"
    large = image_assets / f"large/{large_name}.c"
    large.parent.mkdir(parents=True, exist_ok=True)
    large_text = header()
    large_text += f"extern const uint8_t {map_name}[];\n\n"
    large_text += descriptor(large_name, map_name, 112)
    large.write_text(large_text)
    print(f"112x112 shared: {middle.relative_to(ROOT)}, {large.relative_to(ROOT)}")


def generate_package_icon():
    size = 112
    pixels = resize_rgb(BUS_SOURCE, size)
    output = ROOT / "examples/bus3p/assets/icon.bin"
    output.parent.mkdir(parents=True, exist_ok=True)
    data = b"CR16" + size.to_bytes(2, "little") * 2 + encode_rgb565(pixels)
    output.write_bytes(data)
    print(f"{size}x{size}: {output.relative_to(ROOT)}")


if __name__ == "__main__":
    image_assets = ROOT / "components/esp-brookesia/src/assets/images"
    generate(DEFAULT_SOURCE, image_assets / "small/esp_brookesia_image_small_app_launcher_default_98_98.c",
             "esp_brookesia_image_small_app_launcher_default_98_98", 98)
    generate_shared_default_112(image_assets)
    generate_package_icon()
