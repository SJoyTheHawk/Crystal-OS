#!/usr/bin/env python3
"""Resize Crystal's wallpaper into Brookesia's opaque LVGL 8 true-color format.

Requires ffmpeg on PATH. Run from any directory; the source stays unchanged.
RGB565 builds use a direct pixel buffer, matching the stock wallpaper draw path.
"""
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'reference/crystalos-logo-3d-bluegreen.jpg'
ASSETS = ROOT / 'components/esp-brookesia/src/assets/images'


def convert(size):
    filters = f'scale={size}:{size}:flags=lanczos'
    data = subprocess.check_output([
        'ffmpeg', '-v', 'error', '-i', str(SOURCE), '-vf', filters,
        '-frames:v', '1', '-pix_fmt', 'rgb24',
        '-f', 'rawvideo', 'pipe:1',
    ])
    expected = size * size * 3
    if len(data) != expected:
        raise ValueError(f'Unexpected {size}px output size: {len(data)}')
    return data


def emit_bytes(data):
    return ''.join('  ' + ', '.join(f'0x{x:02x}' for x in data[i:i + 16]) + ',\n'
                   for i in range(0, len(data), 16))


def generate(group, size):
    name = f'esp_brookesia_image_{group}_wallpaper_dark_{size}_{size}'
    path = ASSETS / group / f'{name}.c'
    data = convert(size)
    # Keep the established include and alignment declarations.
    prefix = path.read_text().split('const LV_ATTRIBUTE_MEM_ALIGN', 1)[0]
    prefix = prefix.split('/* Crystal OS launcher wallpaper:', 1)[0]
    prefix = prefix.split('/* Generated by tools/prepare_wallpaper.py', 1)[0]
    output = prefix.rstrip() + '\n\n'
    output += '/* Generated by tools/prepare_wallpaper.py from\n'
    output += ' * reference/crystalos-logo-3d-bluegreen.jpg. Full square artwork, Lanczos resize. */\n'
    output += f'const LV_ATTRIBUTE_MEM_ALIGN LV_ATTRIBUTE_LARGE_CONST LV_ATTRIBUTE_IMG_{name.upper()} uint8_t {name}_map[] = {{\n'
    pixels = list(zip(data[0::3], data[1::3], data[2::3]))
    rgb565 = [(r >> 3) << 11 | (g >> 2) << 5 | b >> 3 for r, g, b in pixels]
    variants = [
        ('LV_COLOR_DEPTH == 1', bytes(int((r | g | b) >= 128) for r, g, b in pixels)),
        ('LV_COLOR_DEPTH == 8', bytes((r >> 5) << 5 | (g >> 5) << 2 | b >> 6 for r, g, b in pixels)),
        ('LV_COLOR_DEPTH == 16 && LV_COLOR_16_SWAP == 0', b''.join(x.to_bytes(2, 'little') for x in rgb565)),
        ('LV_COLOR_DEPTH == 16 && LV_COLOR_16_SWAP != 0', b''.join(x.to_bytes(2, 'big') for x in rgb565)),
        ('LV_COLOR_DEPTH == 32', b''.join(bytes((b, g, r, 255)) for r, g, b in pixels)),
    ]
    for condition, values in variants:
        output += f'#if {condition}\n' + emit_bytes(values) + '#endif\n'
    output += '};\n\n'
    fmt = 'LV_IMG_CF_TRUE_COLOR'
    length = f'{size * size} * LV_COLOR_SIZE / 8'
    output += f'''const lv_img_dsc_t {name} = {{
  .header.cf = {fmt},
  .header.always_zero = 0,
  .header.reserved = 0,
  .header.w = {size},
  .header.h = {size},
  .data_size = {length},
  .data = {name}_map,
}};
'''
    path.write_text(output)
    print(f'{size}x{size}: {fmt} -> {path.relative_to(ROOT)}')


if __name__ == '__main__':
    for group, size in [('small', 240), ('middle', 480), ('large', 720)]:
        generate(group, size)
