#!/usr/bin/env python3
"""Crystal OS USB recovery and coredump extraction tool.

The tool uses the offsets generated by ESP-IDF in ``build/flasher_args.json``
when that file is available.  This keeps recovery safe if the partition table
changes between firmware releases.
"""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import shutil
import struct
import subprocess
import sys
from typing import Iterable, Sequence


DEFAULT_BAUD = "460800"
PARTITION_TABLE_OFFSET = 0x8000
PARTITION_ENTRY_SIZE = 32
PARTITION_TABLE_MAGIC = 0x50AA
PARTITION_TYPE_DATA = 0x01
PARTITION_SUBTYPE_COREDUMP = 0x03


class RecoveryError(RuntimeError):
    """A user-correctable recovery configuration or tool error."""


def _esptool_command() -> list[str]:
    """Return a usable esptool command without requiring a shell wrapper."""
    configured = os.environ.get("CRYSTAL_ESPTOOL")
    if configured:
        return configured.split()
    for executable in ("esptool", "esptool.py"):
        if shutil.which(executable):
            return [executable]
    # This works with current esptool releases installed in a Python venv and
    # produces a useful module-not-found error when the dependency is absent.
    return [sys.executable, "-m", "esptool"]


def run_esptool(arguments: Sequence[str]) -> bool:
    """Run esptool with live output so the user can see flash progress."""
    command = _esptool_command() + list(arguments)
    print(f"Running: {' '.join(command)}")
    try:
        result = subprocess.run(command, check=False)
    except OSError as exc:
        print(f"Error: could not run esptool: {exc}", file=sys.stderr)
        return False
    return result.returncode == 0


def confirm(prompt: str) -> bool:
    """Ask for an explicit yes/no confirmation; EOF cancels safely."""
    while True:
        try:
            response = input(f"{prompt} [y/n]: ").strip().lower()
        except (EOFError, KeyboardInterrupt):
            print("\nAborted.")
            return False
        if response in {"y", "yes"}:
            return True
        if response in {"n", "no"}:
            return False
        print("Please answer y or n.")


def _required_file(directory: Path, name: str) -> Path:
    path = directory / name
    if not path.is_file():
        raise RecoveryError(f"required firmware file not found: {path}")
    return path


def _load_flash_metadata(firmware_dir: Path) -> tuple[dict[str, str], dict[str, str]]:
    """Read ESP-IDF's flash map and return offset/file mappings/settings."""
    metadata_path = firmware_dir / "flasher_args.json"
    if not metadata_path.is_file():
        raise RecoveryError(
            f"{metadata_path} is missing; build the firmware with idf.py build first"
        )
    try:
        metadata = json.loads(metadata_path.read_text(encoding="utf-8"))
        files = metadata["flash_files"]
        settings = metadata.get("flash_settings", {})
    except (OSError, json.JSONDecodeError, KeyError, TypeError) as exc:
        raise RecoveryError(f"invalid ESP-IDF flash metadata: {metadata_path}") from exc
    if not isinstance(files, dict) or not files:
        raise RecoveryError(f"no flash files found in {metadata_path}")
    return {str(offset): str(name) for offset, name in files.items()}, {
        str(key): str(value) for key, value in settings.items()
    }


def _resolve_flash_files(firmware_dir: Path, names: Iterable[str]) -> list[tuple[str, Path]]:
    offsets, _ = _load_flash_metadata(firmware_dir)
    wanted = set(names)
    selected: list[tuple[str, Path]] = []
    for offset, relative_name in offsets.items():
        if Path(relative_name).name in wanted:
            selected.append((offset, _required_file(firmware_dir / Path(relative_name).parent, Path(relative_name).name)))
    missing = wanted - {path.name for _, path in selected}
    if missing:
        raise RecoveryError(
            "firmware metadata does not contain: " + ", ".join(sorted(missing))
        )
    return selected


def _write_flash_arguments(firmware_dir: Path, files: Iterable[tuple[str, Path]]) -> list[str]:
    _, settings = _load_flash_metadata(firmware_dir)
    args = ["--chip", "esp32s3", "--port"]  # port is inserted by caller
    # Keep these options compatible with both esptool 4 and 5.
    args += ["--baud", DEFAULT_BAUD, "--before", "default-reset", "--after", "hard-reset"]
    args += ["write-flash"]
    for key, setting in (("flash_mode", "--flash-mode"), ("flash_freq", "--flash-freq"), ("flash_size", "--flash-size")):
        if settings.get(key):
            args += [setting, settings[key]]
    for offset, path in files:
        args += [offset, str(path)]
    return args


def _flash(port: str, firmware_dir: Path, names: Iterable[str]) -> bool:
    files = _resolve_flash_files(firmware_dir, names)
    arguments = _write_flash_arguments(firmware_dir, files)
    arguments[arguments.index("--port") + 1:arguments.index("--port") + 1] = [port]
    return run_esptool(arguments)


def preserve_recovery(port: str, firmware_dir: Path) -> bool:
    """Restore bootloader, partition table, OTA metadata, and application.

    NVS, the SPIFFS storage partition, and the coredump partition are omitted
    deliberately, so their contents remain intact.
    """
    print("\n=== PRESERVE MODE ===")
    print("This will restore:")
    print("  - Bootloader")
    print("  - Partition table")
    print("  - OTA metadata")
    print("  - Application firmware")
    print("\nThis will keep NVS settings, app storage, and crash history.")
    if not confirm("\nProceed with preserve-mode recovery?"):
        print("Aborted.")
        return False
    try:
        return _flash(port, firmware_dir, {
            "bootloader.bin", "partition-table.bin", "ota_data_initial.bin", "crystal_os.bin"
        })
    except RecoveryError as exc:
        print(f"Error: {exc}", file=sys.stderr)
        return False


def factory_reset_recovery(port: str, firmware_dir: Path) -> bool:
    """Erase the chip, then flash the complete generated image set."""
    print("\n=== FACTORY RESET MODE ===")
    print("WARNING: this permanently erases Wi-Fi credentials, settings, app data, and crash history.")
    if not confirm("Proceed with factory reset?"):
        print("Aborted.")
        return False
    if not confirm("FINAL CONFIRMATION: erase all user data and restore factory state?"):
        print("Aborted.")
        return False
    if not run_esptool(["--chip", "esp32s3", "--port", port, "--before", "default-reset", "--after", "hard-reset", "erase-flash"]):
        return False
    try:
        offsets, _ = _load_flash_metadata(firmware_dir)
        names = {Path(name).name for name in offsets.values()}
        # The generated map includes storage.bin for this project.  If a future
        # build omits it, the remaining boot/app images are still sufficient.
        return _flash(port, firmware_dir, names)
    except RecoveryError as exc:
        print(f"Error: {exc}", file=sys.stderr)
        return False


def _find_coredump_partition(firmware_dir: Path) -> tuple[int, int]:
    """Find the coredump partition in the binary partition table."""
    table = _required_file(firmware_dir / "partition_table", "partition-table.bin")
    data = table.read_bytes()
    for start in range(0, len(data) - PARTITION_ENTRY_SIZE + 1, PARTITION_ENTRY_SIZE):
        magic, ptype, subtype = struct.unpack_from("<HBB", data, start)
        if magic == 0xFFFF:
            break
        if magic != PARTITION_TABLE_MAGIC:
            continue
        offset, size = struct.unpack_from("<II", data, start + 4)
        if ptype == PARTITION_TYPE_DATA and subtype == PARTITION_SUBTYPE_COREDUMP:
            return offset, size
    raise RecoveryError("coredump partition was not found in partition-table.bin")


def extract_coredump(port: str, output_file: Path, firmware_dir: Path) -> bool:
    """Read the coredump partition to a local file."""
    try:
        offset, size = _find_coredump_partition(firmware_dir)
    except RecoveryError as exc:
        print(f"Error: {exc}", file=sys.stderr)
        return False
    output_file.parent.mkdir(parents=True, exist_ok=True)
    print(f"\n=== EXTRACT COREDUMP ({offset:#x}, {size:#x}) ===")
    ok = run_esptool([
        "--chip", "esp32s3", "--port", port, "--before", "default-reset",
        "--after", "no-reset", "read-flash", hex(offset), hex(size), str(output_file)
    ])
    if ok:
        print(f"Coredump saved to: {output_file}")
        print("Decode with: esp-coredump.py info_corefile -t raw <build/crystal_os.elf> <file>")
    return ok


def parse_args(argv: Sequence[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Crystal OS USB recovery tool",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=(
            "Examples:\n"
            "  %(prog)s --port /dev/cu.usbserial-0001 --firmware build --preserve\n"
            "  %(prog)s --port /dev/cu.usbserial-0001 --firmware build --factory-reset\n"
            "  %(prog)s --port /dev/cu.usbserial-0001 --firmware build --extract-coredump coredump.bin"
        ),
    )
    parser.add_argument("-p", "--port", required=True, help="USB serial port")
    parser.add_argument("-f", "--firmware", default="build", help="ESP-IDF build directory (default: build)")
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--preserve", action="store_true", help="restore firmware while preserving user data")
    mode.add_argument("--factory-reset", action="store_true", help="erase all flash and restore factory images")
    mode.add_argument("--extract-coredump", metavar="FILE", type=Path, help="read the coredump partition to FILE")
    return parser.parse_args(argv)


def main(argv: Sequence[str] | None = None) -> int:
    args = parse_args(sys.argv[1:] if argv is None else argv)
    firmware_dir = Path(args.firmware).expanduser().resolve()
    if not firmware_dir.is_dir():
        print(f"Error: firmware directory not found: {firmware_dir}", file=sys.stderr)
        return 2
    if args.extract_coredump:
        success = extract_coredump(args.port, args.extract_coredump.expanduser().resolve(), firmware_dir)
    elif args.factory_reset:
        success = factory_reset_recovery(args.port, firmware_dir)
    else:
        success = preserve_recovery(args.port, firmware_dir)
    if success:
        print("\n✅ Recovery complete!")
        return 0
    print("\n❌ Recovery failed.", file=sys.stderr)
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
